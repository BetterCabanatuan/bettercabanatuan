/**
 * Imports scraped Facebook posts from the city page into the news feed.
 *
 *   npm run import:posts -- <scraper output dir or posts JSON> [...more]
 *
 * Reads every `posts*.json` in a directory (or the files given), keeps posts
 * that match a topic rule below, and rewrites src/data/news.facebook.yaml.
 * That file is generated: edit the rules or SKIP_POST_IDS here, not the YAML.
 * Hand-written items belong in src/data/news.yaml and win over imported ones
 * with the same link.
 *
 * Review the diff before committing. The rules are keyword matches, so a post
 * can slip in or out; add its id to SKIP_POST_IDS to drop it for good.
 */
import {
  existsSync,
  readFileSync,
  readdirSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { basename, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';
import { postsToNewsItems } from '../src/lib/facebookPosts.ts';

const root = fileURLToPath(new URL('..', import.meta.url));
const OUTPUT = join(root, 'src/data/news.facebook.yaml');
const DEFAULT_SOURCE_NAME = 'City Government of Cabanatuan';

/** @type {import('../src/lib/facebookPosts.ts').TopicRule[]} */
const TOPIC_RULES = [
  {
    topic: 'health-services',
    include:
      /city health|health cent|health office|\bCHO\b|M\.?V\.? ?Gallego|MVGCCGH|city hospital|check-?up|konsulta|consultation|bakuna|vaccin|immuni[sz]|measles|tigdas|rubella|\bHPV\b|vitamin a\b|tuberculosis|\bTB\b|chest x-ray|philhealth|YAKAP|family planning|ligation|vasectomy|pre-marriage|\bPMOC\b|mental health|psycholog|CogniCare|rabies|nutrition|dental|wellness clinic|health talk|ophthalm|pediatric|buntis|pre-?natal/i,
    // Posts that mention a health word in passing.
    exclude:
      /civil ?wedding|kasalang|weather update|bantay bagyo|memorandum circular|rapid monitoring|hiring|bigas|weekly news recap|parole|house bill/i,
  },
];

/** Posts the rules match but that should not be published. */
const SKIP_POST_IDS = new Set([]);

function collectInputFiles(args) {
  const files = [];
  for (const arg of args) {
    if (!existsSync(arg)) {
      throw new Error(`Not found: ${arg}`);
    }
    if (statSync(arg).isDirectory()) {
      for (const name of readdirSync(arg).sort()) {
        if (/^posts.*\.json$/.test(name)) files.push(join(arg, name));
      }
    } else {
      files.push(arg);
    }
  }
  return files;
}

function readSourceName(files) {
  for (const file of files) {
    const pageInfo = join(file, '..', 'page_info.json');
    if (existsSync(pageInfo)) {
      const name = JSON.parse(readFileSync(pageInfo, 'utf-8'))?.page_name;
      if (typeof name === 'string' && name.trim()) return name.trim();
    }
  }
  return DEFAULT_SOURCE_NAME;
}

function main() {
  const args = process.argv.slice(2);
  if (!args.length) {
    console.error(
      'Usage: npm run import:posts -- <scraper output dir or posts JSON> [...more]'
    );
    process.exit(1);
  }

  const files = collectInputFiles(args);
  if (!files.length) {
    console.error('No posts*.json files found in the given paths.');
    process.exit(1);
  }

  const posts = files
    .flatMap(file => {
      const parsed = JSON.parse(readFileSync(file, 'utf-8'));
      if (!Array.isArray(parsed)) {
        throw new Error(`${file} is not a JSON array of posts`);
      }
      return parsed;
    })
    .filter(post => !SKIP_POST_IDS.has(post?.id));

  const items = postsToNewsItems(posts, TOPIC_RULES, readSourceName(files));

  const header = [
    '# GENERATED by scripts/import-facebook-posts.mjs — do not edit by hand.',
    '#',
    '# Posts from the official city Facebook page, merged into the news feed by',
    '# src/data/news.ts. To change what appears here, edit the topic rules or',
    '# SKIP_POST_IDS in the script and re-run `npm run import:posts`.',
    `# Sources: ${files.map(f => basename(f)).join(', ')}`,
    '',
  ].join('\n');

  const body = yaml.dump(
    { items },
    { lineWidth: -1, quotingType: "'", forceQuotes: true }
  );
  writeFileSync(OUTPUT, `${header}${body}`);

  const counts = TOPIC_RULES.map(
    rule =>
      `${rule.topic}: ${items.filter(i => i.topics.includes(rule.topic)).length}`
  ).join(', ');
  console.log(
    `Read ${posts.length} posts from ${files.length} file(s); wrote ${items.length} items to ${relative(root, OUTPUT)} (${counts}).`
  );
}

main();
